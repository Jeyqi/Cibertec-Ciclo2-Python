# Ingreso 
numero01 = float(input("Ingresa el primero número: "))
numero02 = float(input("Ingresa el segundo número: "))

# Proceso
suma = numero01 + numero02
resta = numero01 - numero02
multi = numero01 * numero02
divi = numero01 / numero02
resto = numero01 % numero02
potencia = numero01 ** numero02
# Salida
print(f"La suma es: {suma} ")
print(f"La resta es: {resta} ")
print(f"La multiplicación es: {multi} ")
print(f"La división es: {divi} ")
print(f"La resto es: {resto} ")
print(f"La xyz es: {potencia} ")
